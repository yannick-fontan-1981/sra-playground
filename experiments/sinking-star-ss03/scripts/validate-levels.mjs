import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {compileLevel,initialState,stepDetailed,doorsOpen,equal,contains,offset,terrainAt,gateClosed,PullPuzzleSession} from '../dist/core.js';
import {SS03_LEVELS} from '../dist/levels.js';
import {LEVEL_INFO} from '../dist/level-info.js';
import {reachable,solve} from './solver.mjs';
const json=async path=>JSON.parse(await readFile(new URL(path,import.meta.url),'utf8'));
const [witnesses,references,light,presses,legacy,medium]=await Promise.all([
 json('../tests/witnesses.json'),json('../reference/hauling-grids.json'),
 json('../reference/light-piston-grid.json'),json('../reference/level7-design.json'),
 json('../reference/legacy-observation-hashes.json'),json('../reference/level2-design.json'),
]);
const directions=['N','S','W','E'];
const number=p=>p.y*20+p.x;
const hash=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
const session=new PullPuzzleSession(SS03_LEVELS);
const report={game:'SS03',version:'0.4.0',levels:[],legacyObservationParity:[],totalActions:0,totalPulls:0,totalPistonStrokes:0,success:false};
assert.equal(SS03_LEVELS.length,8);assert.equal(witnesses.length,8);assert.equal(LEVEL_INFO.length,8);
const conversion={'*':'o','{':'b','[':'D','G':'g'};
assert.equal(references.levels.filter(l=>l.kind==='transcription').length,2);
for(const reference of references.levels){
 const spec=SS03_LEVELS[reference.level-1];
 assert.equal(spec.id,reference.id);assert.deepEqual(spec.rows,reference.rows);
 if(reference.kind==='transcription')assert.deepEqual(spec.rows,reference.sourceRows.map(r=>[...r].map(c=>conversion[c]??c).join('')));
}
assert.deepEqual(SS03_LEVELS[1],medium.spec);
assert.deepEqual(SS03_LEVELS[6],presses.spec);
assert.deepEqual(SS03_LEVELS[7],light.spec);
assert.deepEqual(witnesses[7].actions,[...light.sourceSolution].map(c=>({U:1,D:2,L:3,R:4})[c]));
assert.equal(light.source.coordinateEvidence.floorTileCount,67);
assert.equal(SS03_LEVELS[7].rows.join('').replaceAll('#','').length,67);

// Hashes were recorded with the previous release, not regenerated by this engine.
for(const baseline of legacy.levels){
 const current=new PullPuzzleSession([SS03_LEVELS[baseline.level-1]]),digest=createHash('sha256');
 digest.update(JSON.stringify(current.observe()));
 for(const action of baseline.actions)digest.update(JSON.stringify(current.action(action)));
 const actual=digest.digest('hex');
 assert.equal(actual,baseline.observationSha256,'L'+baseline.level+' must preserve every '+legacy.version+' public pixel and duration');
 report.legacyObservationParity.push({level:baseline.level,previousLevel:baseline.previousLevel,actions:baseline.actions.length,matched:true,sha256:actual});
}

for(const [i,spec]of SS03_LEVELS.entries()){
 const w=compileLevel(spec),first=initialState(w);let s=first,pulls=0,releaseMoves=0,previousPull=0;
 const pullDirections=new Set(),stoneIds=new Map(first.stones.map((p,j)=>[number(p),j]));
 const stoneAxes=first.stones.map(()=>new Set()),pistonEvents=[];
 assert.equal(witnesses[i].id,spec.id);assert.equal(witnesses[i].level,i+1);assert.equal(session.observe().level,i+1);
 for(const [step,action]of witnesses[i].actions.entries()){
  assert.equal(s.complete,false,spec.id+' witness has moves after completion');
  const detail=stepDetailed(w,s,action),after=detail.state;
  assert.equal(after.failed,false,spec.id+' blocked action '+(step+1));
  assert.ok(!after.dead,spec.id+' fatal action '+(step+1));
  assert.ok(detail.phases.some(p=>p.moves.length),spec.id+' inert witness action '+(step+1));
  assert.equal(after.stones.length,first.stones.length,spec.id+' must preserve every crate');
  assert.deepEqual(after.supports,first.supports);
  let pulled=false;
  for(const phase of detail.phases){
   if(phase.kind==='pull'){pulls++;pulled=true;pullDirections.add(directions[action-1]);previousPull=action;}
   if(phase.kind==='piston')pistonEvents.push({action:step+1,gate:phase.gateIndex,direction:w.gates[phase.gateIndex].direction,movedActors:phase.moves.length});
   const moving=phase.moves.filter(m=>m.actor==='stone').map(m=>({...m,id:stoneIds.get(number(m.from))}));
   for(const motion of moving){assert.notEqual(motion.id,undefined);stoneIds.delete(number(motion.from));}
   for(const motion of moving){stoneIds.set(number(motion.to),motion.id);stoneAxes[motion.id].add(motion.from.x===motion.to.x?'vertical':'horizontal');}
  }
  if(!pulled){if(previousPull&&Math.ceil(previousPull/2)!==Math.ceil(action/2))releaseMoves++;previousPull=0;}
  const observation=session.action(action);
  assert.deepEqual(observation.frames.at(-1),observation.frame);
  assert.deepEqual(observation.availableActionIds,[1,2,3,4]);
  const frameCount=detail.phases.reduce((n,p)=>n+(['pull','piston'].includes(p.kind)?3:1),0)+(after.complete&&i<7?1:0);
  assert.equal(observation.frames.length,frameCount);
  assert.equal(observation.frameDurationsMs.length,frameCount);
  for(const frame of observation.frames){
   assert.equal(frame.length,64);
   assert.ok(frame.every(row=>row.length===64&&row.every(c=>Number.isInteger(c)&&c>=0&&c<16)));
   assert.ok(!frame.flat().includes(1),'No grey destination preview');
  }
  s=after;
 }
 assert.ok(s.complete,spec.id+' must have a complete witness');
 const withoutPull=solve(spec,{disablePull:true,maxStates:10000,maxMs:2000});
 assert.equal(withoutPull.status,'unsolvable',spec.id+' must require pulling; a search limit is not a proof');
 if(w.doors.length)assert.ok(doorsOpen(w,s));
 report.levels.push({level:i+1,id:spec.id,title:spec.title,guidePuzzle:LEVEL_INFO[i].puzzle,sourceUrl:LEVEL_INFO[i].url,
  dimensions:[spec.rows[0].length,spec.rows.length],stones:first.stones.length,buttons:w.buttons.length,pistonGates:w.gates.length,
  initialWalkingCells:w.gates.length?null:reachable(w,first).size,actions:witnesses[i].actions.length,pulls,pullDirections:[...pullDirections].sort(),
  releaseMoves,stonesUsingBothAxes:stoneAxes.filter(s=>s.size>1).length,pistonStrokes:pistonEvents.length,pistonEvents,
  allButtonsOccupiedByStones:w.buttons.every(p=>contains(s.stones,p)),pullsRequired:true,pullAblationStates:withoutPull.states,
  cratesPreserved:true,solved:true,mapSha256:hash(spec.rows),rulesSha256:hash(spec),witnessSha256:hash(witnesses[i].actions)});
}
assert.equal(session.observe().state,'WIN');assert.equal(session.observe().levelsCompleted,8);
const tutorial=report.levels[0];
assert.equal(tutorial.stones,3);assert.equal(tutorial.buttons,3);assert.equal(tutorial.pullDirections.length,4);
assert.ok(tutorial.releaseMoves>=3&&tutorial.stonesUsingBothAxes>=1&&tutorial.initialWalkingCells>=25);
assert.ok(tutorial.allButtonsOccupiedByStones);

// L2: complete-state ablation proves that merely pulling cannot solve the new room.
const mediumWithoutPiston=solve(SS03_LEVELS[1],{disablePistons:true,maxStates:50000,maxMs:8000});
assert.equal(mediumWithoutPiston.status,'unsolvable','The medium level must actually require its press');
report.levels[1].pistonsRequired={method:'exhaustive complete-state search with piston motion disabled',verified:true,states:mediumWithoutPiston.states};
assert.deepEqual(report.levels[1].pistonEvents.map(e=>e.movedActors),[1,2]);

// L7: both empty target niches cannot receive an ordinary pull. The only goal entrance is gated.
const w7=compileLevel(SS03_LEVELS[6]),s7=initialState(w7),exit=w7.circuits.find(c=>c.id==='sortie');
for(const target of exit.buttons){
 assert.ok(!contains(s7.stones,target));
 assert.ok(directions.every((d,i)=>terrainAt(w7,offset(target,d))==='#'||terrainAt(w7,offset(target,directions[i^1]))==='#'));
}
const entrances=directions.map(d=>offset(w7.goal,d)).filter(p=>terrainAt(w7,p)!=='#');
assert.equal(entrances.length,1);assert.ok(equal(entrances[0],w7.gates.find(g=>g.circuit==='sortie').at));
report.levels[6].pistonsRequired={method:'two unfillable target niches and one gated exit',verified:true};
assert.deepEqual(report.levels[6].pistonEvents.map(e=>e.movedActors),[1,2,1]);

// Reach the old trigger through actual inputs: its new remote weight must be present.
const northIndex=w7.gates.findIndex(g=>g.circuit==='presse-nord');
const northButtons=w7.circuits.find(c=>c.id==='presse-nord').buttons;
assert.equal(northButtons.length,2);
let probe=s7;
for(const action of presses.previousRelease.oldProbeActions){
 const detail=stepDetailed(w7,probe,action);probe=detail.state;
 assert.ok(!probe.failed&&!probe.dead);
 assert.ok(!detail.phases.some(p=>p.kind==='piston'&&p.gateIndex===northIndex));
}
assert.ok(equal(probe.hero,northButtons[0]));
assert.ok(contains(probe.stones,w7.gates[northIndex].at));
assert.ok(!contains(probe.stones,northButtons[1]));
assert.equal(gateClosed(w7,probe,northIndex),false);
let active=s7,checkedActivation=false;
for(const action of witnesses[6].actions){
 const detail=stepDetailed(w7,active,action);active=detail.state;
 for(const phase of detail.phases)if(phase.kind==='piston'&&phase.gateIndex===northIndex){
  assert.ok(equal(phase.before.hero,northButtons[0]));
  assert.ok(contains(phase.before.stones,northButtons[1]));
  checkedActivation=true;
 }
}
assert.ok(checkedActivation);
report.levels[6].additionalPlateConstraint={verified:true,oldRoutePrefix:presses.previousRelease.oldProbeActions.length,singleButtonDoesNotPush:true,remoteCrateEnablesNorthPiston:true};
assert.deepEqual(report.levels[7].pistonEvents.map(e=>[e.action,e.direction,e.movedActors]),[[60,'W',2],[86,'W',3],[112,'W',5],[146,'W',6],[146,'N',1]]);
assert.equal(report.levels[7].stones,6);
report.totalActions=report.levels.reduce((n,l)=>n+l.actions,0);
report.totalPulls=report.levels.reduce((n,l)=>n+l.pulls,0);
report.totalPistonStrokes=report.levels.reduce((n,l)=>n+l.pistonStrokes,0);
report.success=true;
await mkdir(new URL('../validation/',import.meta.url),{recursive:true});
await writeFile(new URL('../validation/levels-report.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({success:report.success,version:report.version,levels:report.levels.map(l=>({level:l.level,actions:l.actions,pulls:l.pulls,pistons:l.pistonStrokes})),legacyParity:report.legacyObservationParity.length,totalActions:report.totalActions,totalPulls:report.totalPulls,totalPistonStrokes:report.totalPistonStrokes},null,2));
