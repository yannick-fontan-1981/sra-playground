"""Generate PIPE's independent Python oracle for the browser port.

Run from the repository root:
    python3 scripts/generate-pipe-fixtures.py

The reference engine is unchanged. SHA-256 covers all 4,096 palette indices
of every frame, including every success-animation frame. Only the translated
built-in level titles/notes are omitted; counters, events, geometry, pipes,
network analysis and all other observation fields are compared exactly.

The small constraint solver below creates test witnesses, not agent behavior.
Neither this script nor its fixtures are imported by the application.
"""

