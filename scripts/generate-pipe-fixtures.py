def decode(value: Any) -> Any:
    if isinstance(value, dict):
        if set(value) == {"$number"}:
            return {"NaN": float("nan"), "Infinity": float("inf"),
                    "-Infinity": -float("inf")}[value["$number"]]
        return {key: decode(item) for key, item in value.items()}
    if isinstance(value, list):
        return [decode(item) for item in value]
    return value


def frame_hash(frame: list[list[int]]) -> str:
    assert len(frame) == 64 and all(len(row) == 64 for row in frame)
    assert all(type(pixel) is int and 0 <= pixel <= 15 for row in frame for pixel in row)
    return hashlib.sha256(bytes(pixel for row in frame for pixel in row)).hexdigest()


def snapshot(game: Any, observation: dict[str, Any], translated: bool) -> dict[str, Any]:
    observation = dict(observation)
    observation["frame_sha256"] = frame_hash(observation.pop("frame"))
    observation["frames_sha256"] = [frame_hash(frame) for frame in observation.pop("frames")]
    view = game.view()
    if translated:
        del observation["level_name"]
        del view["title"]
        del view["note"]
    return {"observation": observation, "view": view}


class Scenario:
    def __init__(self, name: str, options: dict[str, Any] | None = None):
        self.options = options or {}
        self.directory: tempfile.TemporaryDirectory[str] | None = None
        kwargs: dict[str, Any] = {}
        if "info" in self.options:
            defaults = {"game_id": reference.GAME_ID, "title": "Pipes", "family": "pipes",
                        "levels": 6, "default_fps": 10}
            kwargs["info"] = SimpleNamespace(**(defaults | self.options["info"]))
        if "levels" in self.options:
            self.directory = tempfile.TemporaryDirectory()
            directory = Path(self.directory.name)
            for i, level in enumerate(self.options["levels"], 1):
                (directory / f"L{i:02d}.json").write_text(json.dumps(level), encoding="utf-8")
            kwargs["levels_dir"] = directory
        self.game = reference.PipesEngine(**kwargs)
        self.translated = "levels" not in self.options
        self.result: dict[str, Any] = {"name": name, "options": self.options,
                                      "translated_copy": self.translated, "steps": []}
        self.add("observe")

    def add(self, method: str, *args: Any) -> dict[str, Any]:
        command = {"method": method, "args": list(args)}
        try:
            observation = getattr(self.game, method)(*decode(list(args)))
        except ValueError:
            self.result["steps"].append({"command": command, "throws": "invalid-input"})
            return {}
        expected = snapshot(self.game, observation, self.translated)
        self.result["steps"].append({"command": command, "expected": expected})
        return observation

    def finish(self) -> dict[str, Any]:
        if self.directory:
            self.directory.cleanup()
        return self.result


def solve_for_test(pipes: list[list[int]], source: list[int]) -> list[list[int]]:
    """Independent arc-consistency search; used exclusively for test generation."""
    size = len(pipes)
    domains = []
    for row in range(size):
        for col in range(size):
            mask = pipes[row][col]
            values = set()
            for _ in range(4):
                if all(0 <= row + dr < size and 0 <= col + dc < size
                       for dr, dc, bit, _ in reference.DIRECTIONS if mask & bit):
                    values.add(mask)
                mask = ((mask << 1) & 15) | (mask >> 3)
            domains.append(values)
    arcs = [(row * size + col, (row + dr) * size + col + dc, bit, opposite)
            for row in range(size) for col in range(size)
            for dr, dc, bit, opposite in reference.DIRECTIONS
            if 0 <= row + dr < size and 0 <= col + dc < size]

    def search(current: list[set[int]]) -> list[list[int]] | None:
        changed = True
        while changed:
            changed = False
            for a, b, bit, opposite in arcs:
                allowed = {value for value in current[a]
                           if any(bool(value & bit) == bool(other & opposite)
                                  for other in current[b])}
                if not allowed:
                    return None
                if allowed != current[a]:
                    current[a] = allowed
                    changed = True
        candidates = [i for i, values in enumerate(current) if len(values) > 1]
        if not candidates:
            grid = [[next(iter(current[row * size + col])) for col in range(size)]
                    for row in range(size)]
            return grid if reference.analyze(grid, source)["solved"] else None
        position = min(candidates, key=lambda i: len(current[i]))
        for candidate in sorted(current[position]):
            branch = [set(values) for values in current]
            branch[position] = {candidate}
            found = search(branch)
            if found:
                return found
        return None

    solution = search(domains)
    assert solution is not None, "The authoritative level has no tree solution"
    return solution


def solve_level(scenario: Scenario) -> dict[str, Any]:
    initial = scenario.game.view()
    solution = solve_for_test(initial["pipes"], initial["source"])
    geometry = initial["geometry"]
    for row in range(initial["size"]):
        for col in range(initial["size"]):
            for _ in range(4):
                if scenario.game.view()["pipes"][row][col] == solution[row][col]:
                    break
                observation = scenario.add("action", 6, {
                    "x": geometry["ox"] + col * geometry["cell"] + geometry["cell"] // 2,
                    "y": geometry["oy"] + row * geometry["cell"] + geometry["cell"] // 2,
                })
                if observation["event"] in ("success", "win"):
                    assert observation["played_level"] == initial["level"]
                    return observation
    raise AssertionError("A solved witness did not produce the expected transition")


