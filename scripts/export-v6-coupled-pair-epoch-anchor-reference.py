#!/usr/bin/env python3
"""Unchanged-source oracle for the coupled-pair epoch-anchor projection.

The full original ObservedCompositionConstraint records each public transition.
The fixture retains its entire result, then separately measures the anchor
projection and the original CoupledPairAccess digest layer. No planner for
paired controls, other series provider, or solved-game claim is exported.
"""
from __future__ import annotations

import copy
import gzip
import hashlib
import inspect
import json
from pathlib import Path
import sys
from types import SimpleNamespace

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
COMMIT = "786dcf51ca57773d8e3a8948ce9ea3655e7baf8e"
SOURCE = ROOT / "reference/v6" / COMMIT / "source"
LAYA = SOURCE / "agents/yf_arc3_v6/laya_proto"
sys.path[:0] = [str(SOURCE), str(LAYA)]

from common_observed_compositions import ObservedCompositionConstraint
from coupled_pair_access import CoupledPairAccess
from neutral_observer import measure
from terminal_composition import identity

INPUT = ROOT / "tests/fixtures/v6-occurrence-reference.json"
captured = json.loads(INPUT.read_text())
POLICY = json.loads(
    (SOURCE / "agents/yf_arc3_v6/morphology_policy/strategy.drm").read_text()
)["declarations"][0]["configuration"]["window_constraints"]["occurrence_recall"]
ANCHOR = "coupled_pair_epoch_anchor"


def plain(value):
    if isinstance(value, dict):
        return {str(key): plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain(item) for item in value]
    if isinstance(value, (set, frozenset)):
        return [plain(item) for item in sorted(value)]
    return value


scenes = {}
journals = []


def captured_scene(name):
    scenes[name] = copy.deepcopy(captured["scenes"][name])
    return name


def controlled_scene(name, rows, *, epoch=1, score=0, revision=1, state="NOT_FINISHED"):
    public = SimpleNamespace(
        frame_rows=copy.deepcopy(rows), frame_packet=[copy.deepcopy(rows)],
        level=epoch, levels_completed=score, state=state, step_index=revision - 1,
        available_action_refs=["ACTION6", "ACTION7"], frame_hash=identity(rows)[:16],
    )
    observation, _ = measure(public, revision, "epoch-anchor-reference")
    scenes[name] = {
        "rows": copy.deepcopy(rows), "public": plain(vars(public)),
        "observation": plain(observation),
    }
    return name


def projection(memory):
    # These cases must remain an anchor-only slice, not silently discard paired
    # motion evidence generated by the unchanged source.
    assert memory.pair_state is None
    assert all(event["kind"] == ANCHOR for event in memory.pair_events)
    return plain(copy.deepcopy({
        "pair_state": memory.pair_state,
        "pair_events": memory.pair_events,
        "pair_initials": memory.pair_initials,
    }))


def snapshot(family):
    memory = family.memory
    return {
        "state": projection(memory),
        "sourceParentDigest": super(CoupledPairAccess, memory).retained_digest(),
        "sourcePairLayerDigest": CoupledPairAccess.retained_digest(memory),
    }


class Driver:
    def __init__(self, name, qualification):
        self.family = ObservedCompositionConstraint()
        self.entry = {
            "id": name, "qualification": qualification,
            "initial": snapshot(self.family), "steps": [],
        }
        journals.append(self.entry)

    def finish_step(self, operation, result):
        expected = snapshot(self.family)
        expected["result"] = plain(copy.deepcopy(result))
        expected["anchorEvents"] = (
            [copy.deepcopy(event) for event in result["events"] if event["kind"] == ANCHOR]
            if result is not None else None
        )
        # Verify the unchanged original adapter can reconstruct the complete
        # event history before generating the next case operation.
        state = copy.deepcopy(self.family.state())
        restored = ObservedCompositionConstraint()
        restored.restore(state)
        assert restored.state() == state
        assert snapshot(restored) == {
            key: expected[key]
            for key in ("state", "sourceParentDigest", "sourcePairLayerDigest")
        }
        self.family = restored
        self.entry["steps"].append({"operation": operation, "expected": expected})
        self.entry["finalState"] = projection(self.family.memory)
        return expected

    def record(self, before, after, *, selected_recall=False, command=None):
        first, second = scenes[before], scenes[after]
        proposal = {}
        if selected_recall:
            proposal = self.family.recall_propose(
                first["observation"], first["rows"], [], 100, POLICY,
            )
            assert proposal and proposal["status"] == "proposed"
            command = copy.deepcopy(proposal["actions"][0])
        if command is None:
            command = {"action_ref": "ACTION6", "data": {"x": 31, "y": 30}}
        result = self.family.record(
            first["observation"], second["observation"], command,
            first["rows"], second["rows"], proposal, 0,
            frames=second["public"]["frame_packet"],
        )
        return self.finish_step(
            {"kind": "record", "before": before, "after": after,
             "command": command, "selectedRecall": selected_recall}, result,
        )

    def apply(self, event):
        # Direct original reducer test. The adapter's public journal appends the
        # same event, exactly as SupportedLineConstraint.record does.
        self.family.memory.apply_event(event)
        self.family.events.append(copy.deepcopy(event))
        return self.finish_step({"kind": "apply", "event": copy.deepcopy(event)}, None)


def main():
    for name in ("memo:0", "memo:1", "memo:2", "program:before", "program:after"):
        captured_scene(name)

    selected = Driver(
        "selected_recall_precedes_one_epoch_anchor",
        "First two real public MEMO transitions, with original recall proposals; not a game campaign.",
    )
    first = selected.record("memo:0", "memo:1", selected_recall=True)
    assert [event["kind"] for event in first["result"]["events"]] == [
        "occurrence_recall_transition", ANCHOR,
    ]
    second = selected.record("memo:1", "memo:2", selected_recall=True)
    assert second["anchorEvents"] == []

    passive = Driver(
        "passive_record_requires_no_recall_or_pair_plan",
        "Same real public MEMO response, observed passively with an empty proposal.",
    )
    passive.record("memo:0", "memo:1")
    passive.record("memo:1", "memo:2")

    packet = Driver(
        "public_packet_anchor_before_program_alignment",
        "Controlled public program packet already retained by the recall oracle; no hidden game state.",
    )
    result = packet.record(
        "program:before", "program:after", command={"action_ref": "ACTION5"},
    )
    assert [event["kind"] for event in result["result"]["events"]] == [
        ANCHOR, "public_program_phase_alignment",
    ]

    rows = copy.deepcopy(scenes["memo:0"]["rows"])
    border = copy.deepcopy(rows)
    border[0][0] = (border[0][0] + 1) % 16
    interior = copy.deepcopy(rows)
    interior[1][1] = (interior[1][1] + 1) % 16
    controlled_scene("same:before", rows)
    controlled_scene("same:after", rows, revision=2)
    controlled_scene("same:score", rows, revision=3, score=1)
    controlled_scene("border:before", border)
    controlled_scene("border:after", border, revision=2)
    controlled_scene("interior:before", interior)
    controlled_scene("interior:after", interior, revision=2)
    controlled_scene("epoch2:before", rows, epoch=2, score=1, revision=3)
    controlled_scene("epoch2:after", rows, epoch=2, score=1, revision=4)
    controlled_scene("epoch10:before", rows, epoch=10, score=9, revision=5)
    controlled_scene("epoch10:after", rows, epoch=10, score=9, revision=6)
    controlled_scene("terminal:after", rows, revision=2, score=1, state="WIN")

    epochs = Driver(
        "anchors_use_before_epoch_and_survive_boundaries_and_returns",
        "Controlled epoch/score metadata around measured public rows; source acquisition and replay only.",
    )
    crossing = epochs.record("same:before", "epoch2:before")
    assert crossing["anchorEvents"][0]["epoch"] == 1
    assert crossing["anchorEvents"][0]["score"] == 0
    epochs.record("epoch2:before", "epoch2:after")
    epochs.record("epoch10:before", "epoch10:after")
    returned = epochs.record("same:before", "same:score")
    assert returned["anchorEvents"] == []
    assert set(epochs.family.memory.pair_initials) == {"1", "2", "10"}

    unchanged = Driver(
        "same_epoch_never_reanchors_on_frame_score_or_observation_changes",
        "Controlled negative acquisitions; first anchor remains authoritative for this epoch.",
    )
    unchanged.record("same:before", "same:after")
    for a, b in (("border:before", "border:after"),
                 ("interior:before", "interior:after"),
                 ("same:score", "terminal:after")):
        assert unchanged.record(a, b)["anchorEvents"] == []

    no_effect = Driver(
        "first_observed_no_effect_still_anchors",
        "A passive no-effect response still records the original before-frame anchor.",
    )
    no_effect.record("same:before", "same:after")
    terminal = Driver(
        "first_terminal_or_score_boundary_still_anchors",
        "The anchor is acquired before any boundary return and describes the before observation.",
    )
    terminal.record("same:before", "terminal:after")

    independent = {}
    for label in ("same", "border", "interior"):
        driver = Driver(
            label + "_digest_separation",
            "Independent current public scenes distinguish whole-frame and interior digests.",
        )
        independent[label] = driver.record(
            label + ":before", label + ":after",
        )["anchorEvents"][0]
    assert independent["same"]["interior_digest"] == independent["border"]["interior_digest"]
    assert independent["same"]["frame_digest"] != independent["border"]["frame_digest"]
    assert independent["same"]["interior_digest"] != independent["interior"]["interior_digest"]

    replay = Driver(
        "reducer_replays_duplicate_epoch_events_without_discarding_history",
        "Direct original apply_event sequence: duplicate epochs overwrite the map, but append the journal.",
    )
    replay.apply(independent["same"])
    replay.apply(independent["border"])
    assert len(replay.family.memory.pair_events) == 2
    assert replay.family.memory.pair_initials["1"] == independent["border"]
    assert replay.record("interior:before", "interior:after")["anchorEvents"] == []

    paths = {
        Path(inspect.getsourcefile(cls))
        for cls in (
            *ObservedCompositionConstraint.__mro__,
            *type(ObservedCompositionConstraint().memory).__mro__,
        )
        if cls is not object
    }
    paths.update({Path(inspect.getsourcefile(identity)), Path(inspect.getsourcefile(measure))})
    sources = {
        str(path.relative_to(SOURCE)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(paths)
    }
    fixture = {
        "provenance": {
            "commit": COMMIT,
            "sourceMethod": "Unchanged full ObservedCompositionConstraint.record/apply_event/restore, with its real MRO.",
            "qualification": "Only the coupled_pair_epoch_anchor projection is ported. The supplied source parent digest proves the original pair-layer formula; no equality with the full ObservedCompositionConstraint digest is claimed. No paired-motion evidence or solver is ported. These are development comparisons, not solved-game or score evidence.",
            "sources": sources,
            "inputFixture": {
                "path": str(INPUT.relative_to(ROOT)),
                "sha256": hashlib.sha256(INPUT.read_bytes()).hexdigest(),
            },
        },
        "scenes": scenes,
        "journals": journals,
    }
    target = ROOT / "tests/fixtures/v6-coupled-pair-epoch-anchor-reference.json.gz"
    payload = (json.dumps(fixture, indent=2, ensure_ascii=False) + "\n").encode()
    target.write_bytes(gzip.compress(payload, mtime=0))
    print(json.dumps({
        "path": str(target.relative_to(ROOT)),
        "journals": len(journals),
        "operations": sum(len(journal["steps"]) for journal in journals),
        "sourceHashes": len(sources),
        "bytes": target.stat().st_size,
    }))


if __name__ == "__main__":
    main()
