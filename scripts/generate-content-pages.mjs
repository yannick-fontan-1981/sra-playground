import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { renderSiteHeader } from '../src/site-header.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const architecture = JSON.parse(await readFile(resolve(root, 'content/architecture.json'), 'utf8'));
const catalog = JSON.parse(await readFile(resolve(root, 'content/videos.json'), 'utf8'));
const benchmark = JSON.parse(await readFile(resolve(root, 'content/arc-agi-3.json'), 'utf8'));
const pages = architecture.pages;
const videos = [...catalog.videos].sort((a, b) => a.episode - b.episode);
const siteOrigin = 'https://sra-playground.yannick-fontan.chatgpt.site';
const repo = 'https://github.com/yannick-fontan-1981/sra-playground';
const escape = value => String(value ?? '').replace(/[&<>"']/g, char => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const anchor = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const number = value => String(value).padStart(2, '0');
const displayDate = value => new Intl.DateTimeFormat('en', { day:'numeric', month:'long', year:'numeric', timeZone:'UTC' }).format(new Date(`${value}T00:00:00Z`));
const arrow = '<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><path d="M5 12h14m-6-6 6 6-6 6"/></svg>';
const external = '<svg class="icon small-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><path d="M7 17 17 7M7 7h10v10"/></svg>';
const play = '<svg viewBox="0 0 28 28" fill="currentColor" aria-hidden="true"><path d="M10 6 23 14 10 22Z"/></svg>';
const archPath = page => page.slug === 'introduction' ? '/architecture.html' : `/architecture/${page.slug}.html`;
const videoPath = video => `/videos/${video.slug}.html`;
const paragraphs = values => (values ?? []).map(value => `<p>${escape(value)}</p>`).join('\n');
const externalLink = (url, label, cls = '') => {
  if (!url.startsWith('https://')) throw new Error(`Unsupported external URL: ${url}`);
  return `<a${cls ? ` class="${cls}"` : ''} href="${escape(url)}" target="_blank" rel="noopener noreferrer">${escape(label)}${external}</a>`;
};
const sources = values => !values?.length ? '' : `<div class="reading-sources">${values.map(item => {
  const url = item.url ?? `${item.path.startsWith('docs/') ? architecture.linkBuilder.repoBase : architecture.linkBuilder.agentBase}${item.path}`;
  return externalLink(url, item.label);
}).join('')}</div>`;

if (new Set(pages.map(page => page.slug)).size !== pages.length) throw new Error('Duplicate chapter slug.');
if (new Set(videos.map(video => video.id)).size !== videos.length) throw new Error('Duplicate video ID.');
if (new Set(videos.map(video => video.slug)).size !== videos.length) throw new Error('Duplicate video slug.');
for (const entry of [...pages, ...videos]) if (!/^[a-z0-9-]+$/.test(entry.slug)) throw new Error(`Invalid page slug: ${entry.slug}`);
for (const video of videos) {
  if (!/^[A-Za-z0-9_-]{11}$/.test(video.id)) throw new Error(`Invalid YouTube ID: ${video.id}`);
  if (!video.thumbnail.startsWith('/videos/')) throw new Error('Video thumbnail must be served locally.');
  if (video.fullText?.kind !== 'youtube-description' || typeof video.fullText.text !== 'string' || !video.fullText.text.trim()) throw new Error(`Missing original episode text: ${video.id}`);
  if (video.fullText.sourceUrl !== video.sourceUrl || video.fullText.language !== 'en' || !video.fullText.author) throw new Error(`Invalid episode text attribution: ${video.id}`);
  for (const slug of video.relatedArchitecture) if (!pages.some(page => page.slug === slug)) throw new Error(`Missing related chapter: ${slug}`);
}

function documentPage({ title, description, path, active, body }) {
  return `<!doctype html>
<!-- Generated by scripts/generate-content-pages.mjs. Edit content/*.json or the template. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#0e0c0c" />
    <meta name="color-scheme" content="dark" />
    <meta name="description" content="${escape(description)}" />
    <title>${escape(title)} · SRA Playground</title>
    <link rel="canonical" href="${siteOrigin}${path}" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
  </head>
  <body class="reading-document">
    <a class="skip-link" href="#content">Skip to content</a>
    ${renderSiteHeader(active)}
    ${body}
    <footer class="site-footer wrap"><span><strong>SRA Playground</strong><span class="footer-separator">/</span>Yannick Fontan</span><div><a href="/">Play the games ${arrow}</a>${externalLink(catalog.channelUrl, 'Yanik_AI')}${externalLink(`${repo}/blob/main/THIRD_PARTY_NOTICES.md`, 'Licenses & notices')}</div></footer>
    <script type="module" src="/src/reading.ts"></script>
  </body>
</html>
`;
}
function chapterNav(current) {
  return `<aside class="reading-sidebar"><a class="sidebar-heading" href="/architecture.html">Architecture</a><nav aria-label="Architecture chapters">${pages.map((page, index) => `<a href="${archPath(page)}"${page.slug === current ? ' class="is-current" aria-current="page"' : ''}><span>${number(index)}</span>${escape(page.navTitle)}</a>`).join('')}</nav><a class="sidebar-series" href="/videos.html">Video series ${arrow}</a></aside>`;
}
function videoNav(current) {
  return `<aside class="reading-sidebar video-sidebar"><a class="sidebar-heading" href="/videos.html">Video series</a><nav aria-label="Video episodes">${videos.map(video => `<a href="${videoPath(video)}"${video.slug === current ? ' class="is-current" aria-current="page"' : ''}><span>${number(video.episode)}</span>${escape(video.displayTitle)}</a>`).join('')}</nav>${externalLink(catalog.channelUrl, 'YouTube channel', 'sidebar-series')}</aside>`;
}
function section(section) {
  return `<section class="reading-section" id="${anchor(section.title)}">
    <h2>${escape(section.title)}</h2>
    ${section.label ? `<p class="example-label">${escape(section.label)}</p>` : ''}
    ${paragraphs(section.paragraphs)}
    ${section.items?.length ? `<${section.ordered ? 'ol' : 'ul'}>${section.items.map(item => `<li>${escape(item)}</li>`).join('')}</${section.ordered ? 'ol' : 'ul'}>` : ''}
    ${section.table ? `<div class="reading-table" role="region" aria-label="${escape(section.title)}" tabindex="0"><table><thead><tr>${section.table.headers.map(header => `<th scope="col">${escape(header)}</th>`).join('')}</tr></thead><tbody>${section.table.rows.map(row => `<tr>${row.map((cell, index) => index === 0 ? `<th scope="row">${escape(cell)}</th>` : `<td>${escape(cell)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>` : ''}
    ${section.code ? `<figure class="reading-code"><pre tabindex="0"><code>${escape(section.code)}</code></pre>${section.codeCaption ? `<figcaption>${escape(section.codeCaption)}</figcaption>` : ''}</figure>` : ''}
    ${sources(section.sources)}
  </section>`;
}
function pager(previous, next, path, label) {
  return `<nav class="reading-pager" aria-label="${label}">${previous ? `<a href="${path(previous)}"><small>Previous</small><span>${escape(previous.navTitle ?? previous.displayTitle)}</span></a>` : '<span></span>'}${next ? `<a class="pager-next" href="${path(next)}"><small>Next</small><span>${escape(next.navTitle ?? next.displayTitle)}${arrow}</span></a>` : '<a class="pager-next" href="/">Playground '+arrow+'</a>'}</nav>`;
}
function relatedVideos(page) {
  const selected = videos.filter(video => video.relatedArchitecture.includes(page.slug));
  return `<section class="related-reading"><h2>Related videos</h2><div>${selected.map(video => `<a href="${videoPath(video)}"><span>Episode ${number(video.episode)}</span><strong>${escape(video.displayTitle)}</strong>${arrow}</a>`).join('')}</div></section>`;
}
function renderChapter(page, index) {
  const directory = page.slug !== 'introduction' ? '' : `<section class="chapter-directory" aria-labelledby="chapters-heading"><h2 id="chapters-heading">Chapters</h2>${pages.slice(1).map((chapter, offset) => `<a href="${archPath(chapter)}"><span>${number(offset + 1)}</span><div><h3>${escape(chapter.navTitle)}</h3><p>${escape(chapter.description)}</p></div>${arrow}</a>`).join('')}</section>`;
  return documentPage({title:page.title,description:page.description,path:archPath(page),active:'architecture',body:`
    <main class="reading-layout wrap">
      ${chapterNav(page.slug)}
      <article class="reading-article" id="content">
        <header class="reading-header"><p class="reading-breadcrumb">Architecture <span>/</span> ${escape(page.navTitle)}</p><h1>${escape(page.title)}</h1><p class="reading-deck">${escape(page.description)}</p></header>
        <div class="reading-intro">${paragraphs(page.intro)}${sources(page.sources)}</div>
        ${page.sections.map(section).join('\n')}
        ${directory}
        ${relatedVideos(page)}
        <p class="source-snapshot">Python source: ${externalLink(`https://github.com/yannick-fontan-1981/ARC-AGI-3-Yannick-Fontan/tree/${architecture.sourceCommit}/agents/yf_arc3_v5`, architecture.sourceCommit.slice(0,12))}</p>
        ${pager(pages[index-1],pages[index+1],archPath,'Chapter navigation')}
      </article>
    </main>`});
}
function renderBenchmark() {
  const path = '/arc-agi-3.html';
  return documentPage({title:benchmark.title,description:benchmark.description,path,active:'arc-agi-3',body:`
    <main class="reading-layout wrap">
      <aside class="reading-sidebar benchmark-sidebar"><a class="sidebar-heading" href="${path}">ARC-AGI-3</a><nav aria-label="On this page">${benchmark.sections.map((item,index)=>`<a href="#${anchor(item.title)}"><span>${number(index+1)}</span>${escape(item.navTitle)}</a>`).join('')}</nav>${externalLink('https://arcprize.org/arc-agi/3','Official benchmark','sidebar-series')}</aside>
      <article class="reading-article benchmark-article" id="content">
        <header class="reading-header"><p class="reading-breadcrumb">ARC-AGI-3 <span>/</span> An introduction</p><h1>${escape(benchmark.title)}</h1><p class="reading-deck">${escape(benchmark.description)}</p></header>
        <div class="reading-intro">${paragraphs(benchmark.intro)}${sources(benchmark.sources)}</div>
        ${benchmark.sections.map(section).join('\n')}
        <section class="related-reading"><h2>Try it for yourself</h2><div class="benchmark-actions"><a class="reading-button" href="/?game=LS20">Play LS20 · official ${arrow}</a><a class="reading-button" href="/?game=CASC">Play CASC · custom ${arrow}</a><a class="reading-button" href="/architecture.html">How SRA is designed ${arrow}</a></div></section>
        <p class="source-snapshot">Official sources checked ${escape(displayDate(benchmark.reviewedDate))}.</p>
      </article>
    </main>`});
}
function videoCard(video) {
  return `<a class="video-card" href="${videoPath(video)}"><div class="video-thumb"><img src="${video.thumbnail}" alt="" width="1280" height="720" loading="lazy"/><span class="video-duration">${escape(video.duration)}</span><span class="video-card-play">${play}</span></div><div class="video-card-meta"><span>Episode ${number(video.episode)}</span><span>${escape(video.games.join(' / '))}${video.gameVersion === 'Legacy' ? ' · Legacy' : ''}</span></div><h2>${escape(video.displayTitle)}</h2><p>${escape(video.topics.slice(0,2).join(' · '))}</p></a>`;
}
function renderVideoIndex() {
  return documentPage({title:'Videos',description:'Yanik_AI: game runs and development notes about the Symbolic Reasoning Agent.',path:'/videos.html',active:'videos',body:`
    <main class="video-index wrap" id="content">
      <header class="video-index-header"><div><p class="reading-breadcrumb">Yanik_AI <span>/</span> Video series</p><h1>Building SRA</h1><p>Game runs and notes on the development of the Symbolic Reasoning Agent.</p></div>${externalLink(catalog.channelUrl, 'Watch the channel', 'reading-button')}</header>
      <div class="video-index-count"><span>${videos.length} episodes</span><span>Yannick Fontan</span></div>
      <div class="video-grid">${videos.map(videoCard).join('')}</div>
      <p class="video-index-note">Each episode includes the full original text published by Yannick Fontan in its YouTube description.</p>
    </main>`});
}
function renderVideo(video, index) {
  const related = video.relatedArchitecture.map(slug=>pages.find(page=>page.slug===slug));
  const gameLinks = video.games.map(code=>`<a class="reading-button" href="/?game=${encodeURIComponent(code)}">Play ${escape(code)}${video.gameVersion === 'Legacy' ? ' (current official version)' : ''}${arrow}</a>`).join('');
  const fullText = video.fullText.text.split(/\n\s*\n/).map(block=>`<p>${escape(block)}</p>`).join('\n');
  const body = `
    <main class="reading-layout wrap">
      ${videoNav(video.slug)}
      <article class="reading-article video-article" id="content">
        <header class="reading-header"><p class="reading-breadcrumb"><a href="/videos.html">Videos</a><span>/</span> Episode ${number(video.episode)}</p><h1>${escape(video.displayTitle)}</h1><div class="video-meta"><span>${escape(video.duration)}</span><span>${escape(video.games.join(' / '))}${video.gameVersion ? ` · ${escape(video.gameVersion)}` : ''}</span><time datetime="${escape(video.date)}">${escape(displayDate(video.date))}</time><a href="#full-text">Read full text ↓</a></div></header>
        <div class="video-player" data-video-id="${escape(video.id)}" data-video-title="${escape(video.displayTitle)}"><button type="button" class="video-launch" aria-label="Play Episode ${number(video.episode)}: ${escape(video.displayTitle)}"><img src="${video.thumbnail}" alt="" width="1280" height="720"/><span class="video-play-label">${play}<span>Play video</span></span></button></div>
        <div class="video-watch-link">${externalLink(video.sourceUrl, 'Watch on YouTube')}${externalLink(catalog.channelUrl, 'Yanik_AI channel')}</div>
        <section class="reading-section episode-text" id="full-text" aria-label="Episode text"><p class="video-source-note">${escape(video.fullText.author)} · Original text from the ${externalLink(video.fullText.sourceUrl, 'YouTube description')}.</p><div class="episode-full-text" lang="${escape(video.fullText.language)}">${fullText}</div></section>
        <section class="related-reading"><h2>Related pages</h2><div>${related.map(page=>`<a href="${archPath(page)}"><span>Architecture</span><strong>${escape(page.navTitle)}</strong>${arrow}</a>`).join('')}</div></section>
        <div class="episode-games">${gameLinks}</div>
        ${pager(videos[index-1],videos[index+1],videoPath,'Episode navigation')}
      </article>
    </main>`;
  return documentPage({title:`Episode ${number(video.episode)} — ${video.displayTitle}`,description:video.summary.slice(0,160),path:videoPath(video),active:'videos',body});
}
async function save(path, html) {
  const target = resolve(root, `.${path}`);
  await mkdir(dirname(target), { recursive:true });
  await writeFile(target, html.replace(/[\t ]+$/gm, ''));
}
for (const [index,page] of pages.entries()) await save(archPath(page),renderChapter(page,index));
await save('/arc-agi-3.html',renderBenchmark());
await save('/videos.html',renderVideoIndex());
for (const [index,video] of videos.entries()) await save(videoPath(video),renderVideo(video,index));
console.log(`Generated the ARC-AGI-3 introduction, ${pages.length} architecture pages, ${videos.length} episode pages, and the video index.`);
