/** Controlled event replay for isolated contract variants, never a game solution. */
function fromEvents(id: string): SharedSeriesConstraint {
  const family = new SharedSeriesConstraint(oracle.policy.recall);
  for (const original of oracle.states[id].events) {
    const event = copy(original);
    assert.ok(['coupled_pair_epoch_anchor', 'coupled_pair_evidence'].includes(event.kind), 'No source ancestor event is silently filtered');
    family.pairs.applyEvent(event); family.events.push(copy(event));
  }
  assert.deepEqual(family.pairs.currentState(), oracle.states[id].pairState);
  const rebuilt = new SharedSeriesConstraint(oracle.policy.recall);
  rebuilt.restore(family.state());
  assert.deepEqual(rebuilt.state(), family.state());
  return rebuilt;
}

test('pair planning oracle identifies unchanged originals and keeps ancestral fallbacks explicit', async () => {
  assert.equal(oracle.provenance.commit, '786dcf51ca57773d8e3a8948ce9ea3655e7baf8e');
  assert.equal(oracle.provenance.sourceModified, false);
  for (const [path, digest] of Object.entries(oracle.provenance.sources)) {
    assert.equal(createHash('sha256').update(await readFile(new URL(path, source))).digest('hex'), digest, path);
  }
  const fallback = oracle.proposalCases.filter((entry: R) => entry.operation === 'pair' && entry.expected === null);
  assert.ok(fallback.length > 10);
  for (const entry of fallback) {
    assert.deepEqual(entry.sourceResult, { status: 'abstained', reason: 'graph_question_not_enabled' });
    assert.match(entry.qualification, /ancestral fallback/);
  }
  assert.equal(oracle.plans.long.actions.length, 16);
  assert.equal(oracle.plans.long.pair_access_plan.route.actions.length, 21,
    'The 21-action route was generated by the original bounded search, not supplied as a plan');
});

for (const journal of oracle.learning) {
  test(`complete common envelope learns the controls before planning: ${journal.id}`, async () => {
    let family = new SharedSeriesConstraint(oracle.policy.recall);
    const store = new NativeKnowledgeStore('coupled-pair-planning-v35', journal.id);
    const expectedEvents: R[] = [];
    for (const [index, step] of journal.steps.entries()) {
      const before = oracle.scenes[step.before], after = oracle.scenes[step.after];
      const result = family.record(before.observation, after.observation, step.command,
        before.rows, after.rows, {}, 0, after.public.frame_packet);
      assert.deepEqual(result, step.expected, 'The whole source common-adapter result is compared');
      assert.deepEqual(family.pairs.currentState(), step.pairState);
      expectedEvents.push(...step.expected.events);
      assert.deepEqual(family.state().events, expectedEvents);
      await store.commit([{ id: 'family_state:public_occurrence_recall', kind: 'family_state', family: family.id, value: family.state() }],
        { workflow: 'v6.composition_strategy.choose', step: 'coupled_support_composition', statement: `acquire.${index}` });
      const retained = store.stateValue('family_state:public_occurrence_recall') as R;
      family = new SharedSeriesConstraint(oracle.policy.recall); family.restore(retained);
      assert.deepEqual(family.state(), retained);
      assert.deepEqual(family.pairs.currentState(), step.pairState);
    }
    assert.deepEqual(family.state().events, journal.sourceState.events);
    const scene = oracle.scenes[journal.finalScene], retained = family.state();
    const proposal = await family.coupledPropose(scene.observation, scene.rows, [], 40, oracle.policy.coupled, 360_000);
    const reference = oracle.proposalCases.find((entry: R) => entry.id === (journal.id === 'small'
      ? 'common_adapter_adds_expected_before_and_source_subquestion' : 'common_adapter_limits_long_prefix_to_16'));
    assert.deepEqual(proposal, reference.expected);
    assert.deepEqual(family.state(), retained, 'Planning adds no retained evidence');
    assert.notEqual(family.state().digest, journal.sourceState.digest,
      'The native supported closure does not claim the complete inherited Python digest');
  });
}

for (const entry of oracle.proposalCases) {
  test(`original pair proposal contract: ${entry.id}`, async () => {
    const family = fromEvents(entry.state), scene = oracle.scenes[entry.scene], retained = family.state();
    const state = family.pairs.currentState(), frozenState = copy(state), observation = copy(entry.observation);
    const rows = copy(scene.rows), inputs = copy(entry.inputs), config = copy(entry.config);
    const run = () => entry.operation === 'common'
      ? family.coupledPropose(observation, rows, inputs, entry.remaining, config, entry.deadline)
      : proposeCoupledPairGraph(state, observation, rows, inputs, entry.maxPrefix, config);
    if (entry.error) {
      await assert.rejects(async () => run(), (error: Error) => error.message === entry.error.message);
    } else assert.deepEqual(await run(), entry.expected);
    assert.deepEqual(family.state(), retained);
    assert.deepEqual(state, frozenState);
    assert.deepEqual(observation, entry.observation);
    assert.deepEqual(rows, scene.rows);
    assert.deepEqual(config, entry.config);
    assert.equal(entry.sourceStateUnchanged, true);
  });
}

