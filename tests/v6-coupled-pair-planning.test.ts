test('one shared family selects coupled planning in goal_access and occurrence recall in window_constraints', async () => {
  const family = createNativeSharedSeriesFamily(oracle.policy.recall, oracle.policy.coupled);
  family.restore(fromEvents('small').state());
  const scene = oracle.scenes['small:5'], retained = family.state();
  assert.equal(family.id, 'public_occurrence_recall');
  assert.ok(family.proposeInGroup);
  const goal = await family.proposeInGroup('goal_access', scene.observation, scene.rows, [], 40, execution);
  assert.deepEqual(goal, oracle.plans.common);
  assert.deepEqual(await family.proposeInGroup('window_constraints', scene.observation, scene.rows, [], 40, execution),
    await family.propose(scene.observation, scene.rows, [], 40, execution));
  assert.equal(await family.proposeInGroup('surface', scene.observation, scene.rows, [], 40, execution), null);
  assert.deepEqual(family.state(), retained);

  const occurrence = JSON.parse(await readFile(new URL('./fixtures/v6-occurrence-reference.json', import.meta.url), 'utf8'));
  const memo = occurrence.scenes['memo:0'], fresh = createNativeSharedSeriesFamily(oracle.policy.recall, oracle.policy.coupled);
  const inputs = new ObservedInputDomain(256).candidates(memo.observation);
  assert.equal(await fresh.proposeInGroup!('goal_access', memo.observation, memo.rows, inputs, 600, execution), null);
  const recalled = await fresh.proposeInGroup!('window_constraints', memo.observation, memo.rows, inputs, 600, execution);
  assert.ok(recalled);
  assert.deepEqual(recalled, await fresh.propose(memo.observation, memo.rows, inputs, 600, execution));
});

test('production source groups reference one retained public_occurrence_recall identity at both source priorities', async () => {
  const runtime = await createNativeV6Runtime(declarations, { now: () => 0 });
  const coverage = runtime.snapshot().coverage as R;
  assert.equal(coverage.registeredFamilies.filter((id: string) => id === 'public_occurrence_recall').length, 1);
  const goal = coverage.sourceGroups.find((group: R) => group.id === 'goal_access');
  const window = coverage.sourceGroups.find((group: R) => group.id === 'window_constraints');
  assert.equal(goal.families.filter((id: string) => id === 'public_occurrence_recall').length, 1);
  assert.equal(window.families.filter((id: string) => id === 'public_occurrence_recall').length, 1);
  assert.ok(coverage.sourceGroups.indexOf(goal) < coverage.sourceGroups.indexOf(window));
  assert.equal(coverage.fullV6Parity, false);
});

function runtimeWithPair(id: string): { runtime: NativeV6Runtime; family: NativeFamily; probes: () => number } {
  const family = createNativeSharedSeriesFamily(oracle.policy.recall, oracle.policy.coupled);
  family.restore(fromEvents(id).state());
  let attempts = 0;
  const fallback: NativeFamily = {
    id: 'unrelated_probe_fixture',
    propose: () => { attempts += 1; return null; },
    before: () => { assert.fail('No unrelated probe can be authorized'); },
    after: () => { assert.fail('No unrelated probe can observe an action'); },
    record: () => { assert.fail('No unrelated probe can acquire evidence'); },
    state: () => ({}), restore: state => { assert.deepEqual(state, {}); },
  };
  const configuration = declarations.strategy.declarations[0]!.configuration;
  const runtime = new NativeV6Runtime({ sourceDigest: 'pair-common-source-contract-v35', now: () => 0,
    families: [family, fallback], maxPointOccurrences: 256,
    groups: [{ id: 'goal_access', families: [family.id] }, { id: 'window_constraints', families: [family.id] },
      { id: 'observed_frontier', families: [fallback.id] }],
    authorityPolicy: declarations.common, callerStrategy: configuration });
  return { runtime, family, probes: () => attempts };
}

test('real common SRC caller stops on causal pair refusal before window recall or unrelated probing', async () => {
  const { runtime, family, probes } = runtimeWithPair('unresolved'), retained = family.state();
  const packet = { ...copy(oracle.scenes['small:5'].public), step_index: 0 };
  const result = await runtime.initialize({ sessionId: 'pair-causal-refusal-contract', observation: packet,
    budgets: { targetLevels: 1, levelActionCaps: [40], maxActions: 40 } }, execution);
  assert.equal(result.kind, 'stopped');
  assert.equal(result.reason, 'frontier_abstained');
  assert.equal(result.command, null); assert.equal(result.authorization, null);
  assert.equal(result.snapshot.actions, 0); assert.equal(result.snapshot.acquiredRecords, 0);
  assert.equal((result.snapshot.caller as R).enabled, true);
  assert.equal((result.snapshot.whyAct as R).enabled, true);
  assert.equal(probes(), 0);
  assert.deepEqual(family.state(), retained);
  assert.equal((result.snapshot.coverage as R).registeredFamilies.filter((id: string) => id === family.id).length, 1);
  assert.equal((result.snapshot.familyStateRefs as R)[family.id].id, 'family_state:public_occurrence_recall');
  assert.equal(result.snapshot.proposal, null);
});

test('real common SRC caller releases the measured pair action through the same family and WHY/ACT', async () => {
  const { runtime, family, probes } = runtimeWithPair('small'), retained = family.state();
  const packet = { ...copy(oracle.scenes['small:5'].public), step_index: 0 };
  const result = await runtime.initialize({ sessionId: 'pair-admitted-source-contract', observation: packet,
    budgets: { targetLevels: 1, levelActionCaps: [40], maxActions: 40 } }, execution);
  assert.equal(result.kind, 'action', result.reason ?? JSON.stringify(result.snapshot.trace));
  assert.deepEqual(result.command, { action_ref: 'ACTION4' });
  assert.ok(result.authorization);
  assert.equal(result.snapshot.lastDecision, 'public_occurrence_recall');
  assert.equal((result.snapshot.proposal as R).kind, 'coupled_pair_access');
  assert.equal((result.snapshot.proposal as R).field_subquestion, 'coupled_support_composition');
  assert.equal((result.snapshot.proposal as R).strategy_receipt.selected, 'goal_access');
  assert.equal((result.snapshot.caller as R).enabled, true);
  assert.equal((result.snapshot.whyAct as R).enabled, true);
  assert.equal(probes(), 0);
  assert.deepEqual(family.state(), retained, 'An offered primitive is not an acquired transition');
  assert.equal(result.snapshot.actions, 0);
});
